     * При отсутствии сети или ошибке безопасно возвращает локальный банк.
     */
    suspend fun fetchTasksOnline(): List<FipiTaskItem> = withContext(Dispatchers.IO) {
        try {
            val url = URI(ONLINE_API_URL).toURL()
            val conn = url.openConnection() as HttpURLConnection
            conn.connectTimeout = 3000
            conn.readTimeout = 3000
            conn.requestMethod = "GET"

            if (conn.responseCode == 200) {
                val jsonStr = conn.inputStream.bufferedReader().use { it.readText() }
                val parsed = Json { ignoreUnknownKeys = true }.decodeFromString<List<FipiTaskItem>>(jsonStr)
                if (parsed.isNotEmpty()) {
                    return@withContext parsed
                }
            }
        } catch (_: Exception) {
            // Оффлайн фоллбэк без ошибок
        }
        return@withContext BUILTIN_TASKS
    }
