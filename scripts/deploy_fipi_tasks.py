def main():
    print("[1/3] Connecting SSH...")
    ssh = paramiko.SSHClient()
    ssh.set_missing_host_key_policy(paramiko.AutoAddPolicy())
    ssh.connect(SERVER_IP, username=SERVER_USER, password=SERVER_PASS, timeout=10)
    sftp = ssh.open_sftp()
    print("      [OK] Connected.")

    print("[2/3] Ensuring remote dirs...")
    for d in ["/var/www/html/api", "/var/www/html/api/fipi"]:
        try:
            sftp.mkdir(d)
        except Exception:
            pass

    print("[3/3] Uploading tasks.json...")
    json_bytes = json.dumps(TASKS, ensure_ascii=False, indent=2).encode('utf-8')
    remote_file = f"{REMOTE_API_DIR}/tasks.json"
    with sftp.open(remote_file, "wb") as f:
        f.write(json_bytes)
    print(f"      [OK] Uploaded {len(TASKS)} tasks to {remote_file}")

    sftp.close()
    ssh.close()
    print("[SUCCESS] FIPI task bank cloud API endpoint is live!")

if __name__ == "__main__":
    main()
